import { describe, expect, it } from 'vitest'
import { formatPhone, phoneHref } from './phone'

/**
 * Показ номера телефона.
 *
 * Номера в базе лежат по-разному: продавцы вводят их и с кодом страны, и без.
 * Интерфейс приписывал «+993» безусловно, и в карточке магазина выводилось
 * «+993 +99361011111».
 */
describe('formatPhone', () => {
  it('не приписывает код страны второй раз', () => {
    expect(formatPhone('+99361011111')).toBe('+99361011111')
  })

  it('приписывает код, когда его нет', () => {
    expect(formatPhone('61011111')).toBe('+993 61011111')
  })

  it('понимает номер, начинающийся с 993 без плюса', () => {
    expect(formatPhone('99361011111')).toBe('+993 61011111')
  })

  it('не спотыкается о пробелы по краям', () => {
    expect(formatPhone('  61011111  ')).toBe('+993 61011111')
  })
})

describe('phoneHref', () => {
  it('убирает пробелы: в ссылке tel: их быть не должно', () => {
    expect(phoneHref('61011111')).toBe('tel:+99361011111')
    expect(phoneHref('+99361011111')).toBe('tel:+99361011111')
  })
})
