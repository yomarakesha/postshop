import { notFound } from '@tanstack/react-router'

/**
 * Отбрасывает маршруты, у которых числовой параметр числом не является.
 *
 * Адрес `/this-does-not-exist` попадал в маршрут товара `/$productId`: строка
 * шла в `Number(...)`, превращалась в `NaN`, и витрина запрашивала
 * `/products/NaN` — сервер отвечал 422, а человек видел «Товар недоступен».
 * То есть на опечатку в адресе страница отвечала «такого товара нет», хотя
 * товара с таким адресом и быть не могло, и отдавала при этом HTTP 200:
 * поисковики считали такую страницу существующей.
 *
 * То же самое было у всех остальных числовых параметров — категории, бренда,
 * магазина, подборки: каждый слал в API свой `NaN`.
 *
 * Проверка идёт до загрузки данных, поэтому запроса с `NaN` не случается
 * вовсе, а `notFound()` показывает обычную страницу «не найдено» из корневого
 * маршрута.
 */
export function requireNumericParams(params: Record<string, string>, keys: Array<string>): void {
  for (const key of keys) {
    // Только цифры: `Number()` принял бы и «1e3», и « 12 », и «0x10».
    if (!/^\d+$/.test(params[key] ?? '')) throw notFound()
  }
}
