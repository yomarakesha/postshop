"""Заслон на разделы, выключенные в настройках.

Прятать раздел только в интерфейсе недостаточно: ручки остаются открытыми, и
любой запрос по прямому адресу продолжает работать. Тогда «выключено» значит
лишь «не видно», а данные всё равно можно завести — и они снова разойдутся с
тем, что происходит в заказах.
"""

from fastapi import HTTPException, status

from app.config import settings


async def require_fbo_enabled() -> None:
    """Пропускает запрос только при включённом складе платформы (FBO).

    Закрываются склады, приёмки и движения по складам платформы. Остатки
    магазинов (FBS) этим не закрываются: их магазин ведёт сам всегда.

    404, а не 403: при выключенном складе раздела не существует, и сообщать о
    его наличии незачем.
    """
    if not settings.FBO_ENABLED:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Platform warehouse (FBO) is disabled (FBO_ENABLED=false).",
        )
