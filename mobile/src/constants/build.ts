/**
 * Показывать ли в профиле пункт «Сервер».
 *
 * Обычному покупателю выбирать адрес сервера незачем — в готовом приложении
 * этого пункта быть не должно. Но тестовые сборки живут как раз на ручном
 * адресе: локальный стек, чужая машина, новый сервер, — и без пункта менять
 * его было бы нечем.
 *
 * Поэтому пункт виден только там, где он нужен:
 * - в режиме разработки (`__DEV__`);
 * - в собранном приложении — если явно включён через
 *   `EXPO_PUBLIC_SHOW_SERVER_SETTING=1`.
 *
 * Переменная живёт в `.env`, который не хранится в репозитории: чужая сборка
 * и сборка для магазина получают её пустой, то есть пункт скрыт по умолчанию.
 *
 * Сам экран `/server-setup` остаётся доступен всегда: на него ведёт редирект
 * с корня, пока адрес не задан, — иначе приложение без адреса не запустить.
 */
export const SHOW_SERVER_SETTING = __DEV__ || process.env.EXPO_PUBLIC_SHOW_SERVER_SETTING === '1'
